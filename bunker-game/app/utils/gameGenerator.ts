// Функции-генераторы
export function generateCharacter(id: number): Character {
  return {
    id,
    name: `Персонаж ${id}`,
    profession: getRandomElement(professions),
    age: Math.floor(Math.random() * 50) + 18, // от 18 до 67 лет
    gender: getRandomElement(genders),
    health: getRandomElement(healthStatuses),
    hobby: getRandomElement(hobbies),
    phobia: getRandomElement(phobias),
    additionalInfo: getRandomElement(additionalInfos),
    trait: getRandomElement(traits)
  };
}

export function generateBunker(): Bunker {
  return {
    size: getRandomElement(bunkerSizes),
    supplies: getRandomElement(bunkerSupplies),
    equipment: getRandomElement(bunkerEquipment),
    duration: getRandomElement(bunkerDurations),
    condition: getRandomElement(bunkerConditions)
  };
}

export function generateCatastrophe(): Catastrophe {
  const typeIndex = Math.floor(Math.random() * catastropheTypes.length);
  
  return {
    type: catastropheTypes[typeIndex],
    description: catastropheDescriptions[typeIndex],
    consequences: catastropheConsequences[typeIndex],
    duration: catastropheDurations[typeIndex]
  };
}

// Вспомогательная функция для получения случайного элемента из массива
function getRandomElement<T>(array: T[]): T {
  return array[Math.floor(Math.random() * array.length)];
} 